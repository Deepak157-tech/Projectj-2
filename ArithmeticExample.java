public class ArithmeticExample {
    public static void main(String []args) {
        
        int x = 9;

        int y = 12;

        System.out.println("x + y = " + (x + y));
        System.out.println("x * y = " + (x * y));
        System.out.println("x / y = " + (x / y)); // integer division
        System.out.println("x % y = " + (x % y)); // remainder
    }
}